namespace NexaUI.Core;

/// <summary>
/// Visual style variants for <see cref="NexaUI.Controls.NexaTabControl"/>.
/// </summary>
public enum NexaTabStyle
{
    /// <summary>
    /// Default underline style with a colored indicator line beneath the active tab.
    /// </summary>
    Default,

    /// <summary>
    /// Underline style with a thin accent line beneath the active tab.
    /// </summary>
    Underline,

    /// <summary>
    /// Pill-shaped tabs with filled background for the active tab.
    /// </summary>
    Pill
}