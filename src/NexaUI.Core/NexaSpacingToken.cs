namespace NexaUI.Core;

/// <summary>
/// Defines the spacing scale steps used across NexaUI.
/// Values are in DIPs (device-independent pixels) and are scaled by DPI at use time.
/// </summary>
public enum NexaSpacingToken
{
    None,
    Xxs,
    Xs,
    Sm,
    Md,
    Lg,
    Xl,
    Xxl,
    Huge
}