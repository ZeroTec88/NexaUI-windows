namespace NexaUI.Core;

/// <summary>
/// Position of a popover relative to its anchor element.
/// </summary>
public enum NexaPopoverPosition
{
    /// <summary>Above the anchor element.</summary>
    Top,
    /// <summary>Below the anchor element.</summary>
    Bottom,
    /// <summary>To the left of the anchor element.</summary>
    Left,
    /// <summary>To the right of the anchor element.</summary>
    Right,
    /// <summary>Top-left corner aligned with anchor.</summary>
    TopLeft,
    /// <summary>Top-right corner aligned with anchor.</summary>
    TopRight,
    /// <summary>Bottom-left corner aligned with anchor.</summary>
    BottomLeft,
    /// <summary>Bottom-right corner aligned with anchor.</summary>
    BottomRight
}